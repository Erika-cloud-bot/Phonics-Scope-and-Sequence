/* Grammar bank, keyed by week. The grammar column of the scope and sequence,
   turned into questions a child can answer on their own.

   Mirrors Grade3_Phonics_Grammar_Scope_and_Sequence.md, the same way
   data/sequence.js does — if you change the grammar focus there, change it
   here too, or the app will drift from your plan.

   ---------------------------------------------------------------------------
   FOUR KINDS OF QUESTION. A week uses whichever ones suit its focus; none is
   compulsory, and a week with none simply shows no grammar activities.

   find   Tap the word in a sentence. The answer is the word in [brackets].
            find: { q: "Which word is the noun?", tag: "the noun",
                    items: ["My [dog] ran fast.", ...] }

   pick   Choose the word that fills the gap. Again the answer is in
          [brackets], and o[] holds the wrong choices offered beside it.
            pick: { q: "Which word finishes the sentence?", items: [
                    { s: "[She] plays the drums.", o: ["Her", "Hers"],
                      why: "She does the action, so it is a subject pronoun." } ] }

   group  Which of two or three groups does a word belong in?
            group: { q: "Common noun or proper noun?", groups: [
                     { label: "common noun", words: ["city", "river"] },
                     { label: "proper noun", words: ["Toronto", "Ottawa"] } ] }

   fix    Three versions of a sentence; only ok is written correctly.
            fix: { q: "Which sentence is written correctly?", items: [
                   { ok: "I am eight years old.",
                     bad: ["I is eight years old.", "I are eight years old."],
                     why: "I always goes with am." } ] }

   ---------------------------------------------------------------------------
   THE BRACKETS ARE THE ANSWER KEY. Exactly one pair per sentence, around one
   word. Write sentences where only that word can be the answer — "Which word
   is the noun?" needs a sentence holding exactly one noun, or a child who
   answers correctly is marked wrong.

   `why` is optional and is the actual teaching. It appears under the answer,
   right or wrong, and the app holds the screen long enough to read it.

   A week can also carry `review: [3, 4, 5]`, which pulls in the questions from
   those weeks — that is how the review and assessment weeks are built. Each
   question keeps the wording it had in its own week, so a mixed review really
   does mix the prompts. A review week may add questions of its own as well.

   Most blocks hold 10–15 questions, and a round asks 10, so a week practised
   twice is not the same ten questions twice.

   Canadian spellings throughout. Edit freely — you know your class. */

